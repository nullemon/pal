#!/usr/bin/env node
/**
 * Copies the eleven SVGs in this folder into `apps/web/lib/chrome/preset-art.ts`, the module the
 * app renders them from.
 *
 * The app cannot read `design/` at runtime — it is not deployed — and a second copy of an SVG
 * under `public/` is a copy that drifts. So the marks are embedded as string constants, and
 * `apps/web/lib/chrome/preset-art.test.ts` fails if this file and the SVGs here disagree.
 * Edit the SVG, run this, commit both.
 *
 *   node design/logos/emit-preset-art.mjs
 */
import { execFileSync } from 'node:child_process'
import { readFileSync, readdirSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import path from 'node:path'

const here = path.dirname(fileURLToPath(import.meta.url))
const out = path.resolve(here, '../../apps/web/lib/chrome/preset-art.ts')

const files = readdirSync(here)
  .filter((f) => /^\d\d-.*\.svg$/.test(f))
  .sort()

const entries = files.map((file) => {
  const id = file.replace(/\.svg$/, '')
  const svg = readFileSync(path.join(here, file), 'utf8').trimEnd()
  return `  '${id}': ${JSON.stringify(svg)},`
})

const body = `import type { LogoPresetId } from './presets'

/**
 * The eleven logo directions from \`design/logos/\`, embedded.
 *
 * Generated by \`node design/logos/emit-preset-art.mjs\` — edit the SVG in \`design/logos/\`, not
 * this file. \`preset-art.test.ts\` fails if the two ever disagree.
 *
 * Embedded rather than served from \`public/\` because these are needed in three places that
 * cannot all read the same file: the header inlines the chosen mark into the HTML (no request,
 * no layout shift), the icon route rasterises it with sharp, and the admin picker previews all
 * eleven. One constant serves all three, and there is no second copy of an SVG to fall out of step.
 *
 * The markup is authored in this repository and is never operator input, which is what makes it
 * safe for the header to inline it.
 */
export const LOGO_PRESET_ART: Record<LogoPresetId, string> = {
${entries.join('\n')}
}
`

writeFileSync(out, body)

/**
 * Hand the result to Biome before anyone sees it. Without this the generated file is valid
 * TypeScript that `biome check` rejects — the entries come out as one long double-quoted line
 * each, where the formatter wants a single-quoted string wrapped onto its own line — so
 * running the command in the doc comment above would leave the tree failing lint. Requoting
 * does not change what the strings contain, so `preset-art.test.ts` compares equal either way.
 */
execFileSync(path.resolve(here, '../../node_modules/.bin/biome'), ['format', '--write', out], {
  stdio: 'inherit',
})

console.log(`wrote ${out} (${files.length} marks)`)
