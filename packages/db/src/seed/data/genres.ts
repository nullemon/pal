export interface GenreSeed {
  slug: string
  name: string
  kind: 'genre' | 'theme' | 'format'
}

const g = (name: string, kind: GenreSeed['kind'] = 'genre'): GenreSeed => ({
  slug: name
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-|-$/g, ''),
  name,
  kind,
})

