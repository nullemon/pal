/** Substitute `{name}` placeholders in a message string. */
export const fmt = (template: string, vars: Record<string, string | number>): string =>
  template.replace(/\{([a-zA-Z_]+)\}/g, (m, k: string) => (k in vars ? String(vars[k]) : m))
